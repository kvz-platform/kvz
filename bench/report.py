#!/usr/bin/env python3
"""Aggregate results/<host>/*.jsonl into results/SUMMARY.md and results/summary.json."""
import glob, json, os, statistics, sys
from collections import defaultdict

ROOT = os.path.join(os.path.dirname(os.path.dirname(os.path.abspath(__file__))), "results")
PLATS = ["kvz", "kvz-v1", "lima-k3s", "apple-cluster"]


def load():
    """Load every JSONL file. run.py appends one run after another (each starts
    with a {"suite":"host"} record); a later run overrides only the suites it
    contains, so partial reruns refresh just what they measured."""
    rows = []
    for f in glob.glob(os.path.join(ROOT, "*", "*.jsonl")):
        recs = []
        for l in open(f):
            try:
                recs.append(json.loads(l))
            except Exception:
                pass
        runs, cur = [], []
        for r in recs:
            if r.get("suite") == "host" and cur:
                runs.append(cur)
                cur = []
            cur.append(r)
        if cur:
            runs.append(cur)
        merged = {}
        for run in runs:
            groups = {}
            for r in run:
                k = (r.get("suite"), r.get("variant") or r.get("op") or r.get("kind") or "")
                groups.setdefault(k, []).append(r)
            merged.update(groups)
        for g in merged.values():
            rows.extend(g)
    return rows


def med(xs):
    xs = [x for x in xs if x is not None]
    return round(statistics.median(xs), 2) if xs else None


def fmt(x, unit=""):
    if x is None:
        return "–"
    if isinstance(x, float) and x >= 100:
        x = round(x)
    return f"{x}{unit}"


def main():
    rows = load()
    hosts = sorted({r["host"] for r in rows if "host" in r})
    hostinfo = {r["host"]: r for r in rows if r.get("suite") == "host"}
    by = defaultdict(list)
    for r in rows:
        by[(r.get("host"), r.get("platform"), r.get("suite"))].append(r)

    out = ["# kvz benchmark summary", "", "Generated by `bench/report.py` from `results/<host>/*.jsonl`. Medians across repetitions.", ""]
    out += ["## Hosts", "", "| host | cpu | cores | RAM | macOS |", "|---|---|---|---|---|"]
    for h in hosts:
        i = hostinfo.get(h, {})
        out.append(f"| {h} | {i.get('cpu','?')} | {i.get('ncpu','?')} | {i.get('mem_gb','?')} GB | {i.get('macos','?')} |")
    out.append("")
    summary = {}

    def table(title, cols, getter, note=None):
        nonlocal out
        out += [f"## {title}", ""]
        if note:
            out += [note, ""]
        out.append("| host | platform | " + " | ".join(c for c, _ in cols) + " |")
        out.append("|---|---|" + "---|" * len(cols))
        for h in hosts:
            for p in PLATS:
                vals = getter(h, p)
                if vals is None:
                    continue
                out.append(f"| {h} | **{p}** | " + " | ".join(fmt(vals.get(k), u) for (_, (k, u)) in cols) + " |")
                summary.setdefault(h, {}).setdefault(p, {}).update({f"{title}:{k}": vals.get(k) for _, (k, u) in cols})
        out.append("")

    def startup(h, p):
        rs = by.get((h, p, "startup"))
        if not rs:
            return None
        g = lambda kind, k: med([r[k] for r in rs if r["kind"] == kind])
        return {"first_api": g("first", "api_ready_s"), "first_node": g("first", "node_ready_s"),
                "re_api": g("restart", "api_ready_s"), "re_node": g("restart", "node_ready_s")}
    table("Control-plane startup", [("first start → API ready", ("first_api", " s")), ("first start → node Ready", ("first_node", " s")),
                                    ("restart → API ready", ("re_api", " s")), ("restart → node Ready", ("re_node", " s"))], startup,
          "kvz `first` = fresh data dir (PKI + etcd init). lima-k3s `first` = boot of an existing stopped VM. apple-cluster always creates a fresh kind node.")

    def idle(h, p):
        rs = by.get((h, p, "idle"))
        if not rs:
            return None
        return {"cpu": med([r["cpu_pct"] for r in rs]), "fp": med([r["footprint_mb"] for r in rs]), "rss": med([r["rss_mb"] for r in rs])}
    table("Idle cost (empty cluster)", [("CPU (% of one core)", ("cpu", "%")), ("phys footprint", ("fp", " MB")), ("RSS", ("rss", " MB"))], idle,
          "Summed over the platform's host processes, including its VMs (guest memory actually touched).")

    def api(h, p):
        rs = by.get((h, p, "api"))
        if not rs:
            return None
        g = lambda op, k: med([r["stats"][k] if k.endswith("_ms") else r.get(k) for r in rs if r.get("op") == op])
        lst = [r for r in rs if str(r.get("op", "")).startswith("list-")]
        return {"create_ops": g("create", "ops_per_s"), "create_p99": g("create", "p99_ms"), "get_ops": g("get", "ops_per_s"),
                "upd_ops": g("get+update", "ops_per_s"), "list_p50": med([r["stats"]["p50_ms"] for r in lst]),
                "watch_p50": g("create->watch-event", "p50_ms"), "del_ops": g("delete", "ops_per_s")}
    table("API server (2000 ConfigMaps, 32 clients)", [("create/s", ("create_ops", "")), ("create p99", ("create_p99", " ms")),
                                                       ("get/s", ("get_ops", "")), ("get+update/s", ("upd_ops", "")),
                                                       ("LIST 2000 p50", ("list_p50", " ms")), ("create→watch p50", ("watch_p50", " ms")),
                                                       ("delete/s", ("del_ops", ""))], api)

    def seq(variant):
        def f(h, p):
            rs = [r for r in by.get((h, p, "pods-seq"), []) if r.get("variant") == variant]
            if not rs:
                return None
            return {"p50": med([r["p50_ms"] for r in rs]), "min": med([r["min_ms"] for r in rs]), "max": med([r["max_ms"] for r in rs])}
        return f
    table("Single pod: create → Ready (nginx:alpine, image cached)", [("p50", ("p50", " ms")), ("min", ("min", " ms")), ("max", ("max", " ms"))], seq("linux-nginx"))

    def burst(variant):
        def f(h, p):
            rs = [r for r in by.get((h, p, "pods"), []) if r.get("variant") == variant]
            st = [r for r in rs if r.get("phase") == "startup"]
            td = [r for r in rs if r.get("phase") == "teardown"]
            if not st:
                return None
            fp = [r.get("footprint_loaded", {}).get("footprint_mb") for r in st]
            return {"wall": med([r["all_ready_wall_s"] for r in st]), "p50": med([r["ready"]["p50_ms"] for r in st]),
                    "p99": med([r["ready"]["p99_ms"] for r in st]), "rate": med([r["pods_per_s"] for r in st]),
                    "fp": med(fp), "td": med([r["all_gone_wall_s"] for r in td])}
        return f
    cols = [("all Ready", ("wall", " s")), ("pods/s", ("rate", "")), ("ready p50", ("p50", " ms")), ("ready p99", ("p99", " ms")),
            ("footprint w/ pods", ("fp", " MB")), ("teardown", ("td", " s"))]
    table("Burst: 20 nginx pods at once", cols, burst("linux-nginx-20"))
    table("Burst: 50 nginx pods at once", cols, burst("linux-nginx-50"))
    table("Burst: 100 nginx pods at once (kvz only)", cols, burst("linux-nginx-100"))
    table("kvz darwin runtime: native processes, 200 pods", cols, burst("darwin-sleep-200"))
    table("kvz darwin runtime: native processes, 500 pods", cols, burst("darwin-sleep-500"))
    table("kvz darwin runtime: single pod create → Ready", [("p50", ("p50", " ms")), ("min", ("min", " ms")), ("max", ("max", " ms"))], seq("darwin-sleep"))
    table("kvz macos runtime: single macOS VM pod create → Ready (SSH up)", [("p50", ("p50", " ms")), ("min", ("min", " ms")), ("max", ("max", " ms"))], seq("macos-vm"))
    table("kvz macos runtime: 2 macOS VMs at once", cols, burst("macos-vm-2"))

    # network
    nets = [r for r in rows if r.get("suite") == "net"]
    if nets:
        out += ["## Pod-to-pod network (iperf3, alpine 3.18, same node)", "", "| host/platform | 1 stream | 4 streams | ping avg |", "|---|---|---|---|"]
        by_label = defaultdict(dict)
        for r in nets:
            lab = r.get("label", "?")
            if "streams" in r and "gbps" in r:
                by_label[lab][r["streams"]] = r["gbps"]
            if "ping" in r:
                parts = r["ping"].split("=")
                by_label[lab]["ping"] = parts[1].split("/")[1] + " ms" if len(parts) > 1 else "?"
        for lab in sorted(by_label):
            d = by_label[lab]
            out.append(f"| {lab} | {d.get(1, '–')} Gbps | {d.get(4, '–')} Gbps | {d.get('ping', '–')} |")
        out.append("")
    extra = [r for r in rows if r.get("suite") in ("container-scaling", "macos-boot", "macos-perf", "multinode", "cpubench")]
    if extra:
        out += ["## Extra probes", "", "```"] + [json.dumps(r) for r in extra] + ["```", ""]
    open(os.path.join(ROOT, "SUMMARY.md"), "w").write("\n".join(out))
    json.dump(summary, open(os.path.join(ROOT, "summary.json"), "w"), indent=1)
    print("\n".join(out))


if __name__ == "__main__":
    main()
